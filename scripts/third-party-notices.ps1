# Regenerates THIRD-PARTY-NOTICES.txt: the licenses of the libraries compiled into kestrel.exe, taken from each
# package's own license files in Cargo's local cache (nothing is downloaded). Run after changing dependencies:
#   powershell -File scripts\third-party-notices.ps1
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
Set-Location $root

$target = ((rustc -vV) | Where-Object { $_ -like 'host:*' }).Split(' ')[1]
# The packages the real build compiles (normal dependencies for this target), not every optional one Cargo knows about.
$built = cargo tree --locked -e normal --target $target --prefix none -f '{p}' |
    ForEach-Object { ($_ -replace ' \((\*|proc-macro)\)', '').Trim() } | Where-Object { $_ } | Sort-Object -Unique
# Filtered to this platform so Cargo doesn't fetch other platforms' packages.
$meta = cargo metadata --format-version 1 --locked --filter-platform $target | ConvertFrom-Json
$packages = $meta.packages | Where-Object { $_.name -ne 'kestrel' -and $built -contains "$($_.name) v$($_.version)" } | Sort-Object name, version

$texts = [ordered]@{}   # license text -> packages that ship it
$missing = @()
foreach ($p in $packages) {
    $dir = Split-Path $p.manifest_path -Parent
    # Top level plus one folder down (egui's fonts keep their licenses in fonts/).
    $files = @(Get-ChildItem $dir -File -Depth 1 | Where-Object { $_.Name -match '^(LICEN[CS]E|COPYING|COPYRIGHT|NOTICE|UNLICENSE|OFL|UFL)|license\.txt$' })
    if ($p.license_file) { $files += Get-Item (Join-Path $dir $p.license_file) }
    $files = $files | Sort-Object FullName -Unique
    if (-not $files) { $missing += $p; continue }
    foreach ($f in $files) {
        $t = ([IO.File]::ReadAllText($f.FullName)).Replace("`r`n", "`n").Trim()
        if (-not $texts.Contains($t)) { $texts[$t] = [System.Collections.Generic.List[string]]::new() }
        $texts[$t].Add("$($p.name) $($p.version)")
    }
}

# Packages without their own file: the standard text of their license, taken from other packages in the cache.
$registry = Split-Path (Split-Path (($meta.packages | Where-Object name -eq 'autocfg' | Select-Object -First 1).manifest_path) -Parent) -Parent
$standard = [ordered]@{
    'MIT'        = "Copyright (c) the authors of each package listed above (see its source repository)`n`n" + @'
Permission is hereby granted, free of charge, to any person obtaining a copy of this software and associated
documentation files (the "Software"), to deal in the Software without restriction, including without limitation
the rights to use, copy, modify, merge, publish, distribute, sublicense, and/or sell copies of the Software, and to
permit persons to whom the Software is furnished to do so, subject to the following conditions:

The above copyright notice and this permission notice shall be included in all copies or substantial portions of
the Software.

THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR IMPLIED, INCLUDING BUT NOT LIMITED TO THE
WARRANTIES OF MERCHANTABILITY, FITNESS FOR A PARTICULAR PURPOSE AND NONINFRINGEMENT. IN NO EVENT SHALL THE AUTHORS OR
COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM, DAMAGES OR OTHER LIABILITY, WHETHER IN AN ACTION OF CONTRACT, TORT OR
OTHERWISE, ARISING FROM, OUT OF OR IN CONNECTION WITH THE SOFTWARE OR THE USE OR OTHER DEALINGS IN THE SOFTWARE.
'@
    'Apache-2.0' = [IO.File]::ReadAllText((Get-ChildItem $registry -Directory -Filter 'autocfg-*' | Select-Object -First 1).FullName + '\LICENSE-APACHE')
    'BSL-1.0'    = [IO.File]::ReadAllText((Get-ChildItem $registry -Directory -Filter 'error-code-*' | Select-Object -First 1).FullName + '\LICENSE')
}

$sb = [Text.StringBuilder]::new()
$line = { param($s) [void]$sb.AppendLine($s) }
& $line 'Kestrel third-party notices'
& $line '==========================='
& $line ''
& $line 'Kestrel is built with the libraries listed below. Each keeps its own license; the full texts follow.'
& $line "Kestrel's own license is in LICENSE.md. Generated by scripts/third-party-notices.ps1 for $target."
& $line ''
& $line "Libraries ($($packages.Count))"
& $line '---------'
foreach ($p in $packages) { & $line ("{0} {1}  ({2})" -f $p.name, $p.version, $(if ($p.license) { $p.license } else { 'see license file' })) }
foreach ($t in $texts.Keys) {
    & $line ''; & $line ('=' * 100); & $line "Used by: $($texts[$t] -join ', ')"; & $line ('=' * 100); & $line ''; & $line $t
}
if ($missing) {
    & $line ''; & $line ('=' * 100)
    & $line 'Packages that ship no license file. Their licenses (as declared by each package) are reproduced below.'
    foreach ($p in $missing) { & $line ("  {0} {1}  ({2})  {3}" -f $p.name, $p.version, $p.license, $p.repository) }
    & $line ('=' * 100)
    foreach ($id in $standard.Keys) {
        if ($missing | Where-Object { $_.license -match [regex]::Escape($id) }) {
            & $line ''; & $line "---- $id ----"; & $line ''; & $line ($standard[$id].Replace("`r`n", "`n").Trim())
        }
    }
    $unknown = $missing | Where-Object { $l = $_.license; -not ($standard.Keys | Where-Object { $l -match [regex]::Escape($_) }) }
    if ($unknown) { throw "No license text available for: $(($unknown | ForEach-Object { "$($_.name) ($($_.license))" }) -join ', ')" }
}
[IO.File]::WriteAllText((Join-Path $root 'THIRD-PARTY-NOTICES.txt'), $sb.ToString().Replace("`r`n", "`n"), [Text.UTF8Encoding]::new($false))
"THIRD-PARTY-NOTICES.txt: $($packages.Count) libraries, $($texts.Count) distinct license texts, $($missing.Count) using a standard text"
